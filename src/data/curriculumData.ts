export function getLessonForWorldAndGrade(grade: Grade, worldId?: string): LessonContent {
  const gradeLesson = LESSONS_BY_GRADE[grade];
  if (!worldId || gradeLesson.worldId === worldId) {
    return gradeLesson;
  }
  if (worldId === 'bosque') return LESSONS_BY_GRADE['1.°'];
  if (worldId === 'montana') return LESSONS_BY_GRADE['4.°'];
  if (worldId === 'biblioteca') {
    return grade === '7.°' ? LESSONS_BY_GRADE['7.°'] : LESSONS_BY_GRADE['6.°'];
  }
  // castillo
  if (grade === '2.°') return LESSONS_BY_GRADE['2.°'];
  if (grade === '5.°' || grade === '6.°' || grade === '7.°') return LESSONS_BY_GRADE['5.°'];
  return LESSONS_BY_GRADE['3.°'];
}

